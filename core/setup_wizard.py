"""Interactive first-run setup for Yuki.

Secrets are stored only in a local environment file with restrictive permissions;
they are never written to config.yaml or printed to the terminal.
"""
from __future__ import annotations

import getpass
import os
from pathlib import Path
import tempfile
from typing import Callable

import yaml

from core.portable_paths import config_path, data_root

_ALLOWED_ENV = {"OPENAI_API_KEY", "YUKI_CLOUD_MODEL", "YUKI_CLOUD_BASE_URL", "YUKI_CLOUD_TASKS"}
_DEFAULT_CLOUD_BASE_URL = "https://api.openai.com/v1"


def local_env_path() -> Path:
    """Return the private local environment file path."""
    return data_root() / ".env"


def load_local_env(path: str | Path | None = None) -> None:
    """Load supported KEY=value entries without overriding shell environment."""
    env_path = Path(path) if path else local_env_path()
    try:
        lines = env_path.read_text(encoding="utf-8").splitlines()
    except FileNotFoundError:
        return
    except OSError as exc:
        raise RuntimeError("Could not read Yuki's local credentials file.") from exc
    for line in lines:
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or "=" not in stripped:
            continue
        key, value = stripped.split("=", 1)
        key, value = key.strip(), value.strip()
        if key in _ALLOWED_ENV and value and key not in os.environ:
            os.environ[key] = value


def _atomic_private_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=".yuki-setup-", dir=str(path.parent), text=True)
    try:
        if os.name == "posix":
            os.chmod(temporary, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(text)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
        if os.name == "posix":
            os.chmod(path, 0o600)
    except Exception:
        try:
            os.unlink(temporary)
        except OSError:
            pass
        raise


def run_setup(
    *,
    config_file: str | Path | None = None,
    env_file: str | Path | None = None,
    input_fn: Callable[[str], str] = input,
    secret_fn: Callable[[str], str] = getpass.getpass,
    output_fn: Callable[[str], None] = print,
) -> None:
    """Run a small guided setup for mock, local Ollama, or hybrid providers."""
    cfg_path = Path(config_file) if config_file else config_path()
    secrets_path = Path(env_file) if env_file else local_env_path()
    try:
        raw = yaml.safe_load(cfg_path.read_text(encoding="utf-8")) or {}
    except FileNotFoundError:
        raw = {}
    except (OSError, yaml.YAMLError) as exc:
        raise RuntimeError("Existing Yuki configuration could not be read safely.") from exc
    if not isinstance(raw, dict):
        raise RuntimeError("Yuki configuration must be a YAML mapping.")

    output_fn("\nYuki first-run setup")
    output_fn("Choose a provider. You can change this later by running: python main.py --setup")
    output_fn("  1) Mock/demo (no model, no API key)")
    output_fn("  2) Local Ollama (local model; no cloud key)")
    output_fn("  3) Hybrid (local Ollama plus explicitly opted-in cloud tasks)")
    choice = input_fn("Provider [1]: ").strip() or "1"
    if choice not in {"1", "2", "3"}:
        raise ValueError("Choose 1, 2, or 3.")

    secrets: dict[str, str] = {}
    if choice == "1":
        raw["provider"] = "mock"
        raw["ollama_model"] = ""
        output_fn("Demo provider selected. Responses are not generated by a real LLM.")
    elif choice == "2":
        model = input_fn("Ollama model name (for example qwen2.5:7b): ").strip()
        if not model or len(model) > 120:
            raise ValueError("Enter a model name of 1–120 characters.")
        raw["provider"] = "ollama"
        raw["ollama_model"] = model
        raw.setdefault("ollama_base_url", "http://127.0.0.1:11434")
        output_fn("Local Ollama selected. Ensure Ollama is running and the model is downloaded.")
    else:
        model = input_fn("Local Ollama model name (for example qwen2.5:7b): ").strip()
        if not model or len(model) > 120:
            raise ValueError("Enter a model name of 1–120 characters.")
        cloud_model = input_fn("Cloud model ID (for example gpt-4.1-mini): ").strip()
        if not cloud_model or len(cloud_model) > 120:
            raise ValueError("Enter a cloud model ID of 1–120 characters.")
        api_key = secret_fn("Cloud API key (input hidden; blank to configure later): ").strip()
        raw["provider"] = "hybrid"
        raw["ollama_model"] = model
        raw.setdefault("ollama_base_url", "http://127.0.0.1:11434")
        if api_key:
            secrets["OPENAI_API_KEY"] = api_key
        secrets["YUKI_CLOUD_MODEL"] = cloud_model
        secrets["YUKI_CLOUD_BASE_URL"] = _DEFAULT_CLOUD_BASE_URL
        task_list = input_fn("Cloud-allowed task labels, comma-separated [none]: ").strip()
        if task_list:
            tasks = [item.strip() for item in task_list.split(",") if item.strip()]
            if len(tasks) > 30 or any(len(item) > 80 for item in tasks):
                raise ValueError("Use at most 30 task labels, each no longer than 80 characters.")
            secrets["YUKI_CLOUD_TASKS"] = ",".join(dict.fromkeys(tasks))
        else:
            secrets["YUKI_CLOUD_TASKS"] = ""
        output_fn("Hybrid mode keeps general tasks local; cloud routing is limited to your listed task labels.")
        if not api_key:
            output_fn("No API key saved. Add OPENAI_API_KEY to the local .env file before using cloud tasks.")

    # Persist non-secret configuration separately from credentials.
    config_text = yaml.safe_dump(raw, sort_keys=False, allow_unicode=True)
    _atomic_private_write(cfg_path, config_text)
    if secrets:
        existing: dict[str, str] = {}
        try:
            for line in secrets_path.read_text(encoding="utf-8").splitlines():
                if "=" in line and not line.lstrip().startswith("#"):
                    key, value = line.split("=", 1)
                    existing[key.strip()] = value.strip()
        except FileNotFoundError:
            pass
        except OSError as exc:
            raise RuntimeError("Existing local credentials file could not be read.") from exc
        existing.update(secrets)
        env_text = "# Yuki local credentials/settings. Never commit this file.\n" + "".join(
            f"{key}={value}\n" for key, value in sorted(existing.items())
            if key in _ALLOWED_ENV
        )
        _atomic_private_write(secrets_path, env_text)
    output_fn(f"Configuration saved to {cfg_path}.")
    if secrets:
        output_fn(f"Private provider settings saved to {secrets_path}; secret values were not displayed.")
    output_fn("Review provider costs, privacy, and model access before sending sensitive data.")
