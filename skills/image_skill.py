"""Optional cloud image generation; prompt is sent to the configured provider."""
from __future__ import annotations
import os
from skills.base import Skill, SkillResult


class ImageGenerationSkill(Skill):
    name = "image_generate"
    description = "Generate an image through the optional OpenAI Images API."
    risk = "medium"
    requires_approval = True

    def run(self, argument=""):
        prompt = argument.strip()
        if not prompt or len(prompt) > 2000:
            return SkillResult(False, "Image prompt must be 1-2000 characters.")
        if not os.environ.get("OPENAI_API_KEY"):
            return SkillResult(False, "Image generation is disabled until OPENAI_API_KEY is configured locally.")
        try:
            from openai import OpenAI
        except ImportError:
            return SkillResult(False, "Install requirements-image.txt to enable the optional image provider.")
        try:
            result = OpenAI().images.generate(model="dall-e-3", prompt=prompt, size="1024x1024",
                                              quality="standard", n=1)
            url = getattr(result.data[0], "url", None) if getattr(result, "data", None) else None
            if not isinstance(url, str) or not url.startswith("https://"):
                return SkillResult(False, "Image provider returned no usable HTTPS result URL.")
            return SkillResult(True, "Image generated by the remote provider. The prompt was sent to that provider.", {
                "url": url, "model": "dall-e-3", "remote_processing": True,
                "note": "The provider's result URL may expire; Yuki has not downloaded or persisted the image.",
            })
        except Exception as exc:
            return SkillResult(False, f"Image generation failed safely ({type(exc).__name__}).")
